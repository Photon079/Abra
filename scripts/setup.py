def check_coral():
    """Check if Coral CLI is installed."""
    try:
        result = subprocess.run(["coral", "--version"], capture_output=True, text=True, timeout=5)
        if result.returncode == 0:
            version = result.stdout.strip()
            success(f"Coral CLI detected: {version}")
            return True
    except (FileNotFoundError, subprocess.TimeoutExpired):
        pass
    return False


def register_coral_sources():
    """Register all source specs with Coral."""
    specs = list(SOURCES_DIR.glob("*.yml")) + list(SOURCES_DIR.glob("*.yaml"))
    if not specs:
        warn("No source spec files found in sources/")
        return
    
    for spec in specs:
        name = spec.stem
        print(f"  Registering {name}...", end=" ", flush=True)
        try:
            result = subprocess.run(
                ["coral", "source", "add", "--file", str(spec)],
                capture_output=True, text=True, timeout=15
            )
            if result.returncode == 0:
                print(f"{GREEN}✓{RESET}")
            else:
                print(f"{YELLOW}⚠ {result.stderr.strip()[:80]}{RESET}")
        except Exception as e:
            print(f"{RED}✗ {e}{RESET}")


def install_dependencies():
    """Install Python dependencies."""
    print("  Installing Python dependencies...")
    try:
        result = subprocess.run(
            [sys.executable, "-m", "pip", "install", "-r", str(PROJECT_ROOT / "requirements.txt"), "-q"],
            capture_output=True, text=True, timeout=120
        )
        if result.returncode == 0:
            success("All Python dependencies installed")
        else:
            warn(f"pip install had issues: {result.stderr.strip()[:100]}")
    except Exception as e:
        error(f"Failed to install dependencies: {e}")


# ──────────────────────────────────────────────
# Main Setup Flow
# ──────────────────────────────────────────────

def main():
    banner()
    config = {}
    
    # Check for existing .env
    if ENV_PATH.exists():
        if not ask_yes_no("Existing .env found. Overwrite with fresh setup?", default=False):
            print(f"\n  {DIM}Keeping existing .env. Run with --force to overwrite.{RESET}")
            # Still offer to register sources
            if check_coral() and ask_yes_no("Register/update Coral sources?"):
                register_coral_sources()
            print(f"\n{GREEN}{BOLD}  Setup complete! Run: python3 main.py{RESET}\n")
            return
    
    # ── Step 1: LLM Provider ──
    section("1/5 · LLM Provider")
    print(f"  Abra needs an LLM to think. Pick your provider:")
    print(f"  {DIM}  1. Gemini (Google — recommended, free tier available)")
    print(f"    2. Groq (fast inference, free tier)")
    print(f"    3. Cerebras (fast inference){RESET}")
    
    provider_choice = ask("Choose provider (1/2/3)", default="1")
    provider_map = {"1": "gemini", "2": "groq", "3": "cerebras"}
    config["LLM_PROVIDER"] = provider_map.get(provider_choice, "gemini")
    
    if config["LLM_PROVIDER"] == "gemini":
        config["GEMINI_API_KEY"] = ask("Gemini API key (https://aistudio.google.com/apikey)")
    elif config["LLM_PROVIDER"] == "groq":
        config["GROQ_API_KEY"] = ask("Groq API key (https://console.groq.com/keys)")
    elif config["LLM_PROVIDER"] == "cerebras":
        config["CEREBRAS_API_KEY"] = ask("Cerebras API key")
    
    # Optional: add secondary provider for fallback
    if config["LLM_PROVIDER"] == "gemini":
        if ask_yes_no("Add Groq as fallback + Whisper voice transcription?", default=False):
            config["GROQ_API_KEY"] = ask("Groq API key (https://console.groq.com/keys)")
    
    success(f"LLM provider: {config['LLM_PROVIDER']}")
    
    # ── Step 2: Notion ──
    section("2/5 · Notion Integration")
    print(f"  Abra writes diary entries and reads tasks from Notion.")
    print(f"  {DIM}  Create an integration at: https://www.notion.so/my-integrations{RESET}")
    
    if ask_yes_no("Set up Notion integration?"):
        config["NOTION_TOKEN"] = ask("Notion integration token (starts with ntn_)")
        config["NOTION_API_KEY"] = config["NOTION_TOKEN"]  # Alias
        config["NOTION_DIARY_DB_ID"] = ask("Diary database ID (32-char hex from URL)", required=False)
        config["NOTION_TASKS_DB_ID"] = ask("Tasks database ID (32-char hex from URL)", required=False)
        config["NOTION_BRAIN_PAGE_ID"] = ask("Brain parent page ID (optional)", required=False)
        success("Notion configured")
    else:
        warn("Skipping Notion. Diary entries will save to local files.")
    
    # ── Step 3: Chess.com ──
    section("3/5 · Chess.com")
    print(f"  Track your chess ratings and game history. No API key needed.")
    
    if ask_yes_no("Connect Chess.com?"):
        config["CHESSCOM_USERNAME"] = ask("Your Chess.com username")
        success(f"Chess.com: {config['CHESSCOM_USERNAME']}")
    else:
        warn("Skipping Chess.com")
    
    # ── Step 4: Strava ──
    section("4/5 · Strava")
    print(f"  Track running, cycling, and fitness data.")
    print(f"  {DIM}  Create an app at: https://www.strava.com/settings/api")
    print(f"    Set callback domain to: localhost{RESET}")
    
    if ask_yes_no("Connect Strava?"):
        config["STRAVA_CLIENT_ID"] = ask("Strava Client ID")
        config["STRAVA_CLIENT_SECRET"] = ask("Strava Client Secret")
        
        if ask_yes_no("Do you already have an access token?", default=False):
            config["STRAVA_ACCESS_TOKEN"] = ask("Strava Access Token")
            config["STRAVA_REFRESH_TOKEN"] = ask("Strava Refresh Token", required=False)
        else:
            print(f"\n  {DIM}  Run this after setup to authenticate:")
            print(f"    python3 coral_startup.py --strava-auth{RESET}\n")
        
        success("Strava configured")
    else:
        warn("Skipping Strava")
    
    # ── Step 5: Write config & finalize ──
    section("5/5 · Finalizing")
    
    # Write .env
    write_env(config)
    
    # Create brain files directory
    print()
    setup_brain_files()
    
    # Install Python deps
    print()
    if ask_yes_no("Install Python dependencies?"):
        install_dependencies()
    
    # Check and register Coral sources
    print()
    has_coral = check_coral()
    if has_coral:
        if ask_yes_no("Register source specs with Coral?"):
            register_coral_sources()
    else:
        warn("Coral CLI not found. Install it: https://withcoral.com/docs/getting-started/installation")
        print(f"  {DIM}  After installing, run: python3 coral_startup.py{RESET}")
    
    # ── Done ──
    print(f"""
{GREEN}{BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━{RESET}
{GREEN}{BOLD}  ✓ Abra is ready!{RESET}

  {BOLD}Start the server:{RESET}
    python3 main.py

  {BOLD}Open the dashboard:{RESET}
    http://127.0.0.1:8000

  {BOLD}Optional next steps:{RESET}
    • Edit brain_files/ to personalize Abra's context
    • Run {CYAN}python3 coral_startup.py --strava-auth{RESET} for Strava OAuth
    • Run {CYAN}coral source lint sources/chesscom.yml{RESET} to validate specs
{GREEN}{BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━{RESET}
""")


if __name__ == "__main__":
    main()
