#!/usr/bin/env python3
"""
Abra Life OS — Interactive Setup
Run once: python3 setup.py
Sets up everything a new user needs in under 5 minutes.
"""

import os
import sys
import subprocess
import shutil
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.resolve()
ENV_PATH = PROJECT_ROOT / ".env"
SOURCES_DIR = PROJECT_ROOT / "sources"
BRAIN_DIR = PROJECT_ROOT / "brain_files"

# ──────────────────────────────────────────────
# Colors for terminal output
# ──────────────────────────────────────────────
CYAN = "\033[96m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
RED = "\033[91m"
BOLD = "\033[1m"
DIM = "\033[2m"
RESET = "\033[0m"


def banner():
    print(f"""
{CYAN}{BOLD}
    ╔═══════════════════════════════════════════╗
    ║          ABRA — Personal Life OS          ║
    ║            Interactive Setup              ║
    ╚═══════════════════════════════════════════╝{RESET}
{DIM}  Voice-first AI life dashboard powered by Coral SQL{RESET}
""")


def ask(prompt, default=None, secret=False, required=True):
    """Prompt user for input with optional default."""
    suffix = f" [{default}]" if default else ""
    if secret:
        suffix += " (hidden)"
    
    while True:
        value = input(f"  {CYAN}→{RESET} {prompt}{suffix}: ").strip()
        if not value and default:
            return default
        if value:
            return value
        if not required:
            return ""
        print(f"  {RED}  This field is required.{RESET}")


def ask_yes_no(prompt, default=True):
    """Ask a yes/no question."""
    suffix = "[Y/n]" if default else "[y/N]"
    answer = input(f"  {CYAN}→{RESET} {prompt} {suffix}: ").strip().lower()
    if not answer:
        return default
    return answer in ("y", "yes")


def section(title):
    print(f"\n{BOLD}{GREEN}━━━ {title} ━━━{RESET}\n")


def success(msg):
    print(f"  {GREEN}✓{RESET} {msg}")


def warn(msg):
    print(f"  {YELLOW}⚠{RESET} {msg}")


def error(msg):
    print(f"  {RED}✗{RESET} {msg}")


def write_env(config: dict):
    """Writes configuration to .env file."""
    lines = ["# Abra Life OS — Auto-generated by setup.py\n"]
    
    sections = {
        "Notion Integration": ["NOTION_TOKEN", "NOTION_DIARY_DB_ID", "NOTION_TASKS_DB_ID", "NOTION_BRAIN_PAGE_ID"],
        "Chess.com": ["CHESSCOM_USERNAME"],
        "LLM Provider": ["LLM_PROVIDER", "GEMINI_API_KEY", "GROQ_API_KEY", "CEREBRAS_API_KEY"],
        "Strava": ["STRAVA_ACCESS_TOKEN", "STRAVA_CLIENT_ID", "STRAVA_CLIENT_SECRET", "STRAVA_REFRESH_TOKEN", "STRAVA_TOKEN_EXPIRES_AT"],
    }
    
    for section_name, keys in sections.items():
        section_keys = {k: v for k, v in config.items() if k in keys and v}
        if section_keys:
            lines.append(f"\n# {section_name}")
            for k, v in section_keys.items():
                lines.append(f'{k}="{v}"')
    
    # Write any remaining keys not in sections
    written = set()
    for keys in sections.values():
        written.update(keys)
    remaining = {k: v for k, v in config.items() if k not in written and v}
    if remaining:
        lines.append("\n# Other")
        for k, v in remaining.items():
            lines.append(f'{k}="{v}"')
    
    ENV_PATH.write_text("\n".join(lines) + "\n")
    success(f"Configuration written to {ENV_PATH.name}")


